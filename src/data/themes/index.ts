export function getTheme(id: string): ThemeDefinition {
  return themes.find(t => t.id === id) ?? themes[0];
}

export function applyTheme(theme: ThemeDefinition): void {
  const root = document.documentElement;
  const t = theme.tokens;
  root.style.setProperty('--color-bg-primary', t.bgPrimary);
  root.style.setProperty('--color-bg-secondary', t.bgSecondary);
  root.style.setProperty('--color-bg-tertiary', t.bgTertiary);
  root.style.setProperty('--color-bg-card', t.bgCard);
  root.style.setProperty('--color-text-primary', t.textPrimary);
  root.style.setProperty('--color-text-secondary', t.textSecondary);
  root.style.setProperty('--color-text-muted', t.textMuted);
  root.style.setProperty('--color-accent', t.accent);
  root.style.setProperty('--color-accent-hover', t.accentHover);
  root.style.setProperty('--color-success', t.success);
  root.style.setProperty('--color-error', t.error);
  root.style.setProperty('--color-warning', t.warning);
  root.style.setProperty('--color-info', t.info);
  root.style.setProperty('--color-border', t.border);
  root.style.setProperty('--color-border-hover', t.borderHover);
  root.style.setProperty('--color-correct', t.correct);
  root.style.setProperty('--color-incorrect', t.incorrect);
  root.style.setProperty('--color-cursor', t.cursor);
}
